"""
Pydantic Schemas for Phase 8: Model Evaluation, Causal LM Metrics, and Baseline Comparison.
"""

from enum import Enum
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class EvaluationStatus(str, Enum):
    """Lifecycle status of a model evaluation job."""
    QUEUED = "queued"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class EvaluationConfig(BaseModel):
    """Configuration settings for model evaluation on a validation dataset."""
    artifact_id: str = Field(description="Target artifact ID (e.g. fine-tuned LoRA/QLoRA adapter)")
    dataset_id: str = Field(description="Selected evaluation dataset ID")
    split: str = Field(default="validation", description="Dataset split to evaluate on (validation, test, or train)")
    max_samples: int = Field(default=50, ge=1, le=500, description="Maximum number of dataset examples to evaluate")
    batch_size: int = Field(default=2, ge=1, le=16, description="Evaluation batch size")
    context_length: int = Field(default=512, ge=64, le=4096, description="Sequence context length for evaluation")
    temperature: float = Field(default=0.7, ge=0.0, le=2.0, description="Sampling temperature for sample generation")
    max_new_tokens: int = Field(default=64, ge=1, le=256, description="Maximum new tokens generated per sample")
    do_sample: bool = Field(default=False, description="Whether to use stochastic sampling or greedy decoding")
    seed: int = Field(default=42, description="Random seed for deterministic sampling")
    run_baseline_comparison: bool = Field(default=True, description="Whether to also evaluate the base model for comparison")
    generate_samples: bool = Field(default=True, description="Whether to generate textual samples for visual inspection")
    num_samples_to_save: int = Field(default=3, ge=0, le=10, description="Number of sample outputs to save with results")


class EvaluationMetrics(BaseModel):
    """Real causal language model evaluation metrics."""
    eval_loss: Optional[float] = Field(default=None, description="Actual cross-entropy token loss")
    perplexity: Optional[float] = Field(default=None, description="Mathematically valid perplexity: exp(eval_loss)")
    perplexity_overflow: bool = Field(default=False, description="True if exp(eval_loss) exceeds mathematical bounds")
    total_tokens: int = Field(default=0, description="Total tokens evaluated across all sequences")
    eval_samples_count: int = Field(default=0, description="Number of dataset samples evaluated")
    eval_runtime_seconds: float = Field(default=0.0, description="Elapsed inference time in seconds")
    samples_per_second: float = Field(default=0.0, description="Throughput in samples per second")
    tokens_per_second: float = Field(default=0.0, description="Throughput in tokens per second")
    unavailable_reasons: Dict[str, str] = Field(default_factory=dict, description="Reasons if any metric could not be calculated")


class EvaluationSample(BaseModel):
    """An individual sample prompt and generated output."""
    sample_id: int = Field(description="Sample index")
    prompt: str = Field(description="Sanitized input prompt")
    expected_output: Optional[str] = Field(default=None, description="Target or ground-truth completion if available")
    fine_tuned_output: Optional[str] = Field(default=None, description="Output generated by the fine-tuned model")
    base_output: Optional[str] = Field(default=None, description="Output generated by the base model (if baseline run)")
    generation_time_ms: float = Field(default=0.0, description="Inference latency for this sample in milliseconds")


class BaselineComparison(BaseModel):
    """Side-by-side metric comparison between the fine-tuned model and base model."""
    base_model_identifier: str = Field(description="Base model identifier")
    base_eval_loss: Optional[float] = Field(default=None, description="Base model evaluation loss")
    base_perplexity: Optional[float] = Field(default=None, description="Base model perplexity")
    fine_tuned_eval_loss: Optional[float] = Field(default=None, description="Fine-tuned model evaluation loss")
    fine_tuned_perplexity: Optional[float] = Field(default=None, description="Fine-tuned model perplexity")
    loss_delta: Optional[float] = Field(default=None, description="fine_tuned_loss - base_loss (negative is improvement)")
    perplexity_delta: Optional[float] = Field(default=None, description="fine_tuned_ppl - base_ppl (negative is improvement)")
    is_improvement: Optional[bool] = Field(default=None, description="True if fine-tuning improved validation loss")
    base_tokens_per_second: Optional[float] = Field(default=None, description="Base model throughput")
    fine_tuned_tokens_per_second: Optional[float] = Field(default=None, description="Fine-tuned model throughput")
    comparison_summary: str = Field(description="Human-readable explanation of comparative performance")
    is_comparable: bool = Field(default=True, description="True if base model was evaluated on the exact same dataset & settings")
    incomparable_reason: Optional[str] = Field(default=None, description="Explanation if comparison was skipped")


class EvaluationRun(BaseModel):
    """Persisted record of an evaluation run."""
    evaluation_id: str = Field(description="Unique evaluation identifier (e.g. eval_123456)")
    run_id: str = Field(description="Associated training run ID")
    artifact_id: str = Field(description="Associated artifact ID")
    dataset_id: str = Field(description="Evaluated dataset ID")
    status: EvaluationStatus = Field(default=EvaluationStatus.QUEUED, description="Lifecycle status")
    config: EvaluationConfig = Field(description="Evaluation configuration settings")
    created_at: str = Field(description="UTC timestamp of creation")
    started_at: Optional[str] = Field(default=None, description="UTC timestamp when evaluation started")
    completed_at: Optional[str] = Field(default=None, description="UTC timestamp when evaluation completed")
    elapsed_seconds: float = Field(default=0.0, description="Total execution duration in seconds")
    metrics: Optional[EvaluationMetrics] = Field(default=None, description="Computed evaluation metrics")
    samples: List[EvaluationSample] = Field(default_factory=list, description="Generated sample comparisons")
    baseline_comparison: Optional[BaselineComparison] = Field(default=None, description="Baseline comparison if performed")
    error_message: Optional[str] = Field(default=None, description="Safe error details if evaluation failed")


class EvaluationListResponse(BaseModel):
    """Paginated list of evaluation runs."""
    evaluations: List[EvaluationRun] = Field(default_factory=list, description="List of evaluation runs")
    total: int = Field(default=0, description="Total matching evaluations")
    page: int = Field(default=1, description="Current page")
    page_size: int = Field(default=20, description="Page size")


class EvaluationResultsResponse(BaseModel):
    """Detailed results for a specific evaluation run."""
    evaluation_id: str = Field(description="Evaluation ID")
    status: EvaluationStatus = Field(description="Evaluation status")
    metrics: Optional[EvaluationMetrics] = Field(default=None, description="Evaluation metrics")
    samples: List[EvaluationSample] = Field(default_factory=list, description="Sample outputs")
    baseline_comparison: Optional[BaselineComparison] = Field(default=None, description="Baseline comparison")
    error_message: Optional[str] = Field(default=None, description="Safe error message if failed")
